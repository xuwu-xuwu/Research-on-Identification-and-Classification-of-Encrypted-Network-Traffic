import argparse
import copy
import json
import math
import random
import sys
from pathlib import Path

import numpy as np
import pandas as pd
import torch
from sklearn.metrics import classification_report, confusion_matrix
from torch import nn
from torch.utils.data import DataLoader, Dataset, TensorDataset

PROJECT_ROOT = Path(__file__).resolve().parents[2]
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

from src.encryption_method.unified_benchmark_utils import compute_metrics


SUPPORTED_MODELS = ("deep_packet_cnn", "et_bert_transformer", "tfe_gnn")


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Run paper-method benchmark on the 5-class PCAP dataset.")
    parser.add_argument(
        "--data",
        default="data/paper_benchmark/encryption_method_5class_pcap_v1/packet/flows_5class.npz",
        help="Packet benchmark NPZ generated by build_paper_benchmark_dataset.py.",
    )
    parser.add_argument(
        "--output-dir",
        default="outputs/encryption_method/paper_methods_5class_v1",
        help="Output directory.",
    )
    parser.add_argument("--models", nargs="+", default=list(SUPPORTED_MODELS), choices=SUPPORTED_MODELS)
    parser.add_argument("--epochs", type=int, default=8)
    parser.add_argument("--batch-size", type=int, default=32)
    parser.add_argument("--learning-rate", type=float, default=1e-3)
    parser.add_argument("--weight-decay", type=float, default=1e-4)
    parser.add_argument("--patience", type=int, default=4)
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--device", default="auto", help="auto/cpu/cuda")
    parser.add_argument("--max-transformer-tokens", type=int, default=512)
    parser.add_argument("--max-graph-bytes", type=int, default=512)
    return parser.parse_args()


def set_seed(seed: int) -> None:
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    if torch.cuda.is_available():
        torch.cuda.manual_seed_all(seed)


def resolve_device(device_arg: str) -> torch.device:
    if device_arg == "auto":
        return torch.device("cuda" if torch.cuda.is_available() else "cpu")
    return torch.device(device_arg)


def split_indices(split: np.ndarray, key: str) -> np.ndarray:
    return np.where(split.astype(str) == key)[0].astype(np.int64)


class DeepPacketCNN(nn.Module):
    def __init__(self, packet_size: int, num_classes: int) -> None:
        super().__init__()
        self.net = nn.Sequential(
            nn.Conv1d(1, 64, kernel_size=7, stride=2, padding=3),
            nn.BatchNorm1d(64),
            nn.ReLU(),
            nn.MaxPool1d(kernel_size=3, stride=2, padding=1),
            nn.Conv1d(64, 128, kernel_size=5, stride=2, padding=2),
            nn.BatchNorm1d(128),
            nn.ReLU(),
            nn.AdaptiveMaxPool1d(16),
        )
        self.classifier = nn.Sequential(
            nn.Flatten(),
            nn.Linear(128 * 16, 256),
            nn.ReLU(),
            nn.Dropout(0.25),
            nn.Linear(256, num_classes),
        )

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        x = x.float().unsqueeze(1) / 255.0
        return self.classifier(self.net(x))


class PositionalEncoding(nn.Module):
    def __init__(self, dim: int, max_len: int) -> None:
        super().__init__()
        position = torch.arange(max_len, dtype=torch.float32).unsqueeze(1)
        div_term = torch.exp(torch.arange(0, dim, 2, dtype=torch.float32) * (-math.log(10000.0) / dim))
        pe = torch.zeros(max_len, dim, dtype=torch.float32)
        pe[:, 0::2] = torch.sin(position * div_term)
        pe[:, 1::2] = torch.cos(position * div_term)
        self.register_buffer("pe", pe.unsqueeze(0), persistent=False)

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        return x + self.pe[:, : x.size(1)]


class ETBertStyleTransformer(nn.Module):
    def __init__(self, num_classes: int, max_tokens: int, dim: int = 128) -> None:
        super().__init__()
        self.pad_id = 256
        self.sep_id = 257
        self.embedding = nn.Embedding(258, dim, padding_idx=self.pad_id)
        self.position = PositionalEncoding(dim, max_len=max_tokens)
        layer = nn.TransformerEncoderLayer(
            d_model=dim,
            nhead=4,
            dim_feedforward=384,
            dropout=0.15,
            activation="gelu",
            batch_first=True,
        )
        self.encoder = nn.TransformerEncoder(layer, num_layers=2)
        self.classifier = nn.Sequential(
            nn.LayerNorm(dim),
            nn.Linear(dim, 128),
            nn.GELU(),
            nn.Dropout(0.2),
            nn.Linear(128, num_classes),
        )

    def forward(self, token_ids: torch.Tensor) -> torch.Tensor:
        mask = token_ids.eq(self.pad_id)
        embedded = self.position(self.embedding(token_ids))
        encoded = self.encoder(embedded, src_key_padding_mask=mask)
        valid = (~mask).float().unsqueeze(-1)
        pooled = (encoded * valid).sum(dim=1) / valid.sum(dim=1).clamp(min=1.0)
        return self.classifier(pooled)


class ByteGraphDataset(Dataset):
    def __init__(self, byte_sequences: np.ndarray, labels: np.ndarray, max_graph_bytes: int) -> None:
        self.labels = torch.from_numpy(labels.astype(np.int64, copy=False))
        self.node_features, self.adjacency = self._build_graphs(byte_sequences, max_graph_bytes)

    @staticmethod
    def _build_graphs(byte_sequences: np.ndarray, max_graph_bytes: int) -> tuple[torch.Tensor, torch.Tensor]:
        flat = byte_sequences.reshape(byte_sequences.shape[0], -1)[:, :max_graph_bytes]
        node_features = np.zeros((len(flat), 256, 1), dtype=np.float32)
        adjacency = np.zeros((len(flat), 256, 256), dtype=np.float32)
        for row_index, seq in enumerate(flat):
            counts = np.bincount(seq.astype(np.int64), minlength=256).astype(np.float32)
            if counts.sum() > 0:
                counts = counts / counts.sum()
            node_features[row_index, :, 0] = counts
            if len(seq) > 1:
                source = seq[:-1].astype(np.int64)
                target = seq[1:].astype(np.int64)
                adjacency[row_index, source, target] += 1.0
                adjacency[row_index, target, source] += 1.0
            adjacency[row_index] += np.eye(256, dtype=np.float32)
            degree = adjacency[row_index].sum(axis=1, keepdims=True)
            adjacency[row_index] = adjacency[row_index] / np.maximum(degree, 1.0)
        return torch.from_numpy(node_features), torch.from_numpy(adjacency)

    def __len__(self) -> int:
        return int(len(self.labels))

    def __getitem__(self, index: int) -> tuple[torch.Tensor, torch.Tensor, torch.Tensor]:
        return self.node_features[index], self.adjacency[index], self.labels[index]


class TFEGNNStyleClassifier(nn.Module):
    def __init__(self, num_classes: int, hidden_dim: int = 64) -> None:
        super().__init__()
        self.node_embed = nn.Sequential(nn.Linear(1, hidden_dim), nn.ReLU())
        self.gcn1 = nn.Linear(hidden_dim, hidden_dim)
        self.gcn2 = nn.Linear(hidden_dim, hidden_dim)
        self.classifier = nn.Sequential(
            nn.Linear(hidden_dim * 2, 128),
            nn.ReLU(),
            nn.Dropout(0.25),
            nn.Linear(128, num_classes),
        )

    def forward(self, node_features: torch.Tensor, adjacency: torch.Tensor) -> torch.Tensor:
        h = self.node_embed(node_features)
        h = torch.relu(self.gcn1(torch.bmm(adjacency, h)))
        h = torch.relu(self.gcn2(torch.bmm(adjacency, h)))
        pooled = torch.cat([h.mean(dim=1), h.max(dim=1).values], dim=1)
        return self.classifier(pooled)


def make_transformer_tokens(x: np.ndarray, max_tokens: int) -> np.ndarray:
    flat = x.reshape(x.shape[0], -1)
    tokens = np.full((len(flat), max_tokens), 256, dtype=np.int64)
    usable = min(flat.shape[1], max_tokens)
    tokens[:, :usable] = flat[:, :usable].astype(np.int64)
    return tokens


def class_weights(y: np.ndarray, num_classes: int) -> torch.Tensor:
    counts = np.bincount(y, minlength=num_classes).astype(np.float32)
    weights = counts.sum() / np.maximum(counts, 1.0)
    weights = weights / weights.mean()
    return torch.from_numpy(weights.astype(np.float32))


def train_epoch(model: nn.Module, loader: DataLoader, criterion: nn.Module, optimizer: torch.optim.Optimizer, device: torch.device) -> float:
    model.train()
    losses: list[float] = []
    for batch in loader:
        optimizer.zero_grad(set_to_none=True)
        if len(batch) == 2:
            x, y = batch
            logits = model(x.to(device))
        else:
            node_features, adjacency, y = batch
            logits = model(node_features.to(device), adjacency.to(device))
        y = y.to(device)
        loss = criterion(logits, y)
        loss.backward()
        torch.nn.utils.clip_grad_norm_(model.parameters(), max_norm=5.0)
        optimizer.step()
        losses.append(float(loss.item()))
    return float(np.mean(losses)) if losses else 0.0


def predict(model: nn.Module, loader: DataLoader, device: torch.device) -> tuple[np.ndarray, np.ndarray]:
    model.eval()
    y_true: list[int] = []
    y_pred: list[int] = []
    with torch.no_grad():
        for batch in loader:
            if len(batch) == 2:
                x, y = batch
                logits = model(x.to(device))
            else:
                node_features, adjacency, y = batch
                logits = model(node_features.to(device), adjacency.to(device))
            y_true.extend(y.numpy().tolist())
            y_pred.extend(torch.argmax(logits, dim=1).cpu().numpy().tolist())
    return np.asarray(y_true, dtype=np.int64), np.asarray(y_pred, dtype=np.int64)


def build_loaders(
    model_name: str,
    x: np.ndarray,
    x_first: np.ndarray,
    y: np.ndarray,
    split: np.ndarray,
    args: argparse.Namespace,
) -> tuple[DataLoader, DataLoader, DataLoader, np.ndarray, np.ndarray, np.ndarray]:
    train_idx = split_indices(split, "train")
    valid_idx = split_indices(split, "valid")
    test_idx = split_indices(split, "test")

    if model_name == "deep_packet_cnn":
        train_ds = TensorDataset(torch.from_numpy(x_first[train_idx]), torch.from_numpy(y[train_idx]))
        valid_ds = TensorDataset(torch.from_numpy(x_first[valid_idx]), torch.from_numpy(y[valid_idx]))
        test_ds = TensorDataset(torch.from_numpy(x_first[test_idx]), torch.from_numpy(y[test_idx]))
    elif model_name == "et_bert_transformer":
        tokens = make_transformer_tokens(x, args.max_transformer_tokens)
        train_ds = TensorDataset(torch.from_numpy(tokens[train_idx]), torch.from_numpy(y[train_idx]))
        valid_ds = TensorDataset(torch.from_numpy(tokens[valid_idx]), torch.from_numpy(y[valid_idx]))
        test_ds = TensorDataset(torch.from_numpy(tokens[test_idx]), torch.from_numpy(y[test_idx]))
    elif model_name == "tfe_gnn":
        train_ds = ByteGraphDataset(x[train_idx], y[train_idx], max_graph_bytes=args.max_graph_bytes)
        valid_ds = ByteGraphDataset(x[valid_idx], y[valid_idx], max_graph_bytes=args.max_graph_bytes)
        test_ds = ByteGraphDataset(x[test_idx], y[test_idx], max_graph_bytes=args.max_graph_bytes)
    else:
        raise ValueError(f"Unsupported model: {model_name}")

    return (
        DataLoader(train_ds, batch_size=args.batch_size, shuffle=True, num_workers=0),
        DataLoader(valid_ds, batch_size=args.batch_size, shuffle=False, num_workers=0),
        DataLoader(test_ds, batch_size=args.batch_size, shuffle=False, num_workers=0),
        train_idx,
        valid_idx,
        test_idx,
    )


def build_model(model_name: str, x: np.ndarray, x_first: np.ndarray, num_classes: int, args: argparse.Namespace) -> nn.Module:
    if model_name == "deep_packet_cnn":
        return DeepPacketCNN(packet_size=x_first.shape[1], num_classes=num_classes)
    if model_name == "et_bert_transformer":
        return ETBertStyleTransformer(num_classes=num_classes, max_tokens=args.max_transformer_tokens)
    if model_name == "tfe_gnn":
        return TFEGNNStyleClassifier(num_classes=num_classes)
    raise ValueError(f"Unsupported model: {model_name}")


def write_model_outputs(
    output_dir: Path,
    model_name: str,
    metrics: dict[str, object],
    y_true: np.ndarray,
    y_pred: np.ndarray,
    label_names: list[str],
) -> None:
    model_dir = output_dir / model_name
    model_dir.mkdir(parents=True, exist_ok=True)
    metrics_path = model_dir / "metrics.json"
    metrics_path.write_text(json.dumps(metrics, indent=2, ensure_ascii=False), encoding="utf-8")
    report = classification_report(y_true, y_pred, labels=np.arange(len(label_names)), target_names=label_names, digits=4, zero_division=0)
    (model_dir / "classification_report.txt").write_text(report, encoding="utf-8")
    cm = confusion_matrix(y_true, y_pred, labels=np.arange(len(label_names)))
    pd.DataFrame(cm, index=label_names, columns=label_names).to_csv(model_dir / "confusion_matrix.csv")


def run_model(model_name: str, bundle: np.lib.npyio.NpzFile, args: argparse.Namespace, device: torch.device) -> dict[str, object]:
    x = bundle["x"]
    x_first = bundle["x_first"]
    y = bundle["y"].astype(np.int64)
    split = bundle["split"]
    label_names = bundle["labels"].tolist()
    num_classes = len(label_names)

    train_loader, valid_loader, test_loader, train_idx, valid_idx, test_idx = build_loaders(model_name, x, x_first, y, split, args)
    model = build_model(model_name, x, x_first, num_classes, args).to(device)
    criterion = nn.CrossEntropyLoss(weight=class_weights(y[train_idx], num_classes).to(device), label_smoothing=0.02)
    optimizer = torch.optim.AdamW(model.parameters(), lr=args.learning_rate, weight_decay=args.weight_decay)

    best_state = copy.deepcopy(model.state_dict())
    best_valid = -1.0
    stale_epochs = 0
    history: list[dict[str, float]] = []

    for epoch in range(1, args.epochs + 1):
        train_loss = train_epoch(model, train_loader, criterion, optimizer, device)
        y_valid, pred_valid = predict(model, valid_loader, device)
        valid_metrics = compute_metrics(y_valid, pred_valid, label_names)
        history.append({"epoch": float(epoch), "train_loss": train_loss, "valid_f1_macro": float(valid_metrics["f1_macro"])})
        if valid_metrics["f1_macro"] > best_valid:
            best_valid = float(valid_metrics["f1_macro"])
            best_state = copy.deepcopy(model.state_dict())
            stale_epochs = 0
        else:
            stale_epochs += 1
        if stale_epochs >= args.patience:
            break

    model.load_state_dict(best_state)
    y_test, pred_test = predict(model, test_loader, device)
    metrics = compute_metrics(y_test, pred_test, label_names)
    metrics.update(
        {
            "model_name": model_name,
            "data_path": str(args.data),
            "samples_train": int(len(train_idx)),
            "samples_valid": int(len(valid_idx)),
            "samples_test": int(len(test_idx)),
            "epochs_requested": int(args.epochs),
            "epochs_ran": int(len(history)),
            "best_valid_f1_macro": float(best_valid),
            "batch_size": int(args.batch_size),
            "learning_rate": float(args.learning_rate),
            "device": str(device),
            "history": history,
        }
    )
    write_model_outputs(Path(args.output_dir), model_name, metrics, y_test, pred_test, label_names)
    return {
        "model_name": model_name,
        "accuracy": metrics["accuracy"],
        "f1_macro": metrics["f1_macro"],
        "f1_weighted": metrics["f1_weighted"],
        "macro_recall": metrics["macro_recall"],
        "samples_test": metrics["samples_test"],
    }


def main() -> None:
    args = parse_args()
    set_seed(args.seed)
    device = resolve_device(args.device)
    output_dir = Path(args.output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    bundle = np.load(Path(args.data), allow_pickle=False)
    comparison_rows = []
    for model_name in args.models:
        print(f"[paper-method] training {model_name}")
        comparison_rows.append(run_model(model_name, bundle, args, device))

    comparison_df = pd.DataFrame(comparison_rows).sort_values(["f1_macro", "accuracy"], ascending=[False, False])
    comparison_df.to_csv(output_dir / "comparison.csv", index=False)
    (output_dir / "comparison.json").write_text(json.dumps(comparison_rows, indent=2, ensure_ascii=False), encoding="utf-8")
    markdown = [
        "# Paper-Method 5-Class PCAP Benchmark",
        "",
        f"- Data: `{Path(args.data)}`",
        f"- Models: `{', '.join(args.models)}`",
        "",
        comparison_df.to_markdown(index=False),
        "",
    ]
    (output_dir / "comparison.md").write_text("\n".join(markdown), encoding="utf-8")
    print("Paper-method benchmark finished.")
    print(comparison_df.to_string(index=False))


if __name__ == "__main__":
    main()
