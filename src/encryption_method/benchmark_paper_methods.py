#!/usr/bin/env python
"""Benchmark packet/sequence paper methods on the shared PCAP benchmark.

Implemented local comparison branches:
- Deep Packet style: byte-level 1D CNN over the first packet.
- ET-BERT style: byte-token Transformer over a multi-packet flow sequence.
- TFE-GNN style: byte-transition graph with a compact GCN classifier.

These branches share the same flow samples, labels, and train/valid/test split.
"""

